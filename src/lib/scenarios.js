// Dialogo a voce sugli argomenti di una lezione (fine lezione, allenamento di oggi, conversazione libera)
export function lessonTalk(l, { kind = 'lesson', maxTurns = 4 } = {}) {
  const prompts = l.speaking?.prompts || []
  const words = l.words.slice(0, 24).map(w => w.en.replace(/^to /, ''))
  return {
    kind, ref: kind + ':' + l.id, title: `Lezione ${l.id}: ${l.title}`, maxTurns, voice: 1,
    level: levelFor(l.id),
    partner: 'il tutor, nel ruolo di un collega o di un cliente',
    goalIt: `Parlare del tema della lezione («${l.title}») usando le sue parole e frasi.`,
    goal: `Talk about "${l.titleEn}" using the words and phrases of the lesson.`,
    scenario: `A realistic work conversation about "${l.titleEn}". Context: ${l.dialogue?.context || ''} You play a colleague or client of the student, and you guide the conversation on this topic.`,
    words: words.join(', ') + '; ' + l.phrases.slice(0, 8).map(p => p.en).join(' | '),
    targets: [...words, ...l.phrases.map(p => p.en)],
    opener: prompts[0] ? { en: prompts[0].en, it: prompts[0].it } : { en: 'Hi! Shall we talk about today\'s topic?', it: 'Ciao! Parliamo del tema di oggi?' },
    questions: prompts.slice(1).map(p => p.en),
    phrases: l.phrases.slice(0, 8).map(p => ({ en: p.en, it: p.it })),
  }
}
